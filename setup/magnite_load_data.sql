-- ============================================================================
-- Affinity Solutions x Magnite — Standalone Data Load
-- Run AFTER setup/01_environment.sql (database, schemas, CSV_FORMAT, stages).
-- Loads only Magnite objects; does not touch any other platform's tables.
--
-- 1. From the repo root, upload the Magnite files and app to the stages:
--
--   for d in magnite_consumer ml cleanroom; do
--     snow stage copy "data/$d/" "@AFFINITY_DEMO.APPS.DATA_STAGE/$d/" --overwrite --connection <conn>
--   done
--   snow stage copy apps/magnite_app/streamlit_app.py "@AFFINITY_DEMO.APPS.STREAMLIT_STAGE/magnite_app/" --overwrite --connection <conn>
--
--   (Only files named *magnite* in ml/ and cleanroom/ are used below.)
--
-- 2. Run this script in Snowflake.
--
-- Note: the raw Streaming / DV+ log tables, training set and ML model objects
-- are not exported (size). The dashboard runs entirely on the tables below.
-- ============================================================================

USE DATABASE AFFINITY_DEMO;
USE WAREHOUSE AFFINITY_GEN_WH;

CREATE SCHEMA IF NOT EXISTS AFFINITY_DEMO.MAGNITE_CONSUMER
  COMMENT = 'Magnite SSP consumer-side data (Streaming + DV+ log-level exposure data)';

-- ============================================================================
-- CLEANROOM — Magnite identity match
-- ============================================================================
USE SCHEMA CLEANROOM;

CREATE OR REPLACE TABLE MAGNITE_MATCH_RATE_SUMMARY (
  PLATFORM VARCHAR, MATCH_CODE VARCHAR, MATCH_LEVEL VARCHAR, WATERFALL_STEP NUMBER,
  MATCHED_COUNT NUMBER, HH_ONLY_COUNT NUMBER, PCT_OF_MATCHED FLOAT, PCT_OF_TOTAL_AFS FLOAT
);
COPY INTO MAGNITE_MATCH_RATE_SUMMARY FROM @AFFINITY_DEMO.APPS.DATA_STAGE/cleanroom/magnite_match_rate_summary.csv FILE_FORMAT = AFFINITY_DEMO.APPS.CSV_FORMAT;

CREATE OR REPLACE TABLE CROSSWALK_MAGNITE (
  AFS_INDID VARCHAR, AFS_HHID VARCHAR, CLIENT_AFS_INDID VARCHAR, CLIENT_AFS_HHID VARCHAR,
  MATCH_CODE VARCHAR, MATCH_LEVEL VARCHAR, RETURN_CODE VARCHAR, WATERFALL_STEP NUMBER,
  MATCH_DESCRIPTION VARCHAR, PLATFORM VARCHAR, CLIENT_INDID VARCHAR, MATCH_TIMESTAMP TIMESTAMP_LTZ
);
COPY INTO CROSSWALK_MAGNITE FROM @AFFINITY_DEMO.APPS.DATA_STAGE/cleanroom/crosswalk_magnite.csv.gz FILE_FORMAT = AFFINITY_DEMO.APPS.CSV_FORMAT;

CREATE OR REPLACE TABLE GROUND_TRUTH_MAGNITE (
  INDID VARCHAR, HHID VARCHAR, MAGNITE_USER_ID VARCHAR, ASSIGNED_MATCH_CODE VARCHAR, ASSIGNED_MATCH_LEVEL VARCHAR
);
COPY INTO GROUND_TRUTH_MAGNITE FROM @AFFINITY_DEMO.APPS.DATA_STAGE/cleanroom/ground_truth_magnite.csv FILE_FORMAT = AFFINITY_DEMO.APPS.CSV_FORMAT;

-- ============================================================================
-- ML — Magnite model results
-- ============================================================================
USE SCHEMA ML;

