);
COPY INTO MAGNITE_VALIDATION_DECILES FROM @AFFINITY_DEMO.APPS.DATA_STAGE/ml/magnite_validation_deciles.csv FILE_FORMAT = AFFINITY_DEMO.APPS.CSV_FORMAT;

CREATE OR REPLACE TABLE MAGNITE_FEATURE_IMPORTANCE (
  MODEL VARCHAR, RANK NUMBER, FEATURE VARCHAR, IMPORTANCE_SCORE FLOAT
);
COPY INTO MAGNITE_FEATURE_IMPORTANCE FROM @AFFINITY_DEMO.APPS.DATA_STAGE/ml/magnite_feature_importance.csv FILE_FORMAT = AFFINITY_DEMO.APPS.CSV_FORMAT;

CREATE OR REPLACE TABLE MAGNITE_HOLDOUT_RESULTS (
  SET_NAME VARCHAR, IMPRESSIONS NUMBER, PURCHASES NUMBER, PURCHASE_RATE_PCT FLOAT,
