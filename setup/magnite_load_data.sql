-- Model registry: add (or refresh) only the Magnite rows
CREATE TABLE IF NOT EXISTS MODEL_REGISTRY (
  MODEL_NAME VARCHAR(100), MODEL_TYPE VARCHAR, SCHEMA_LOCATION VARCHAR, DESCRIPTION VARCHAR,
  TARGET_TYPE VARCHAR, TRAINING_DATA VARCHAR, FEATURES VARCHAR, KEY_METRIC VARCHAR, CREATED_AT TIMESTAMP_LTZ
);
DELETE FROM MODEL_REGISTRY WHERE MODEL_NAME LIKE 'MAGNITE%';
COPY INTO MODEL_REGISTRY FROM @AFFINITY_DEMO.APPS.DATA_STAGE/ml/magnite_model_registry.csv FILE_FORMAT = AFFINITY_DEMO.APPS.CSV_FORMAT;

